import { type AuctionShowResponseDto } from '@/shared/api/dto';

import { type AuctionEntity } from '../model/auction-entity.types';

/**
 * Собирает проекцию detail из канонической сущности.
 *
 * Тело тривиально: detail — надмножество, и проекция совпадает с ним. Маппер
 * существует ради симметрии с `toListItem` и как единственная названная точка,
 * где detail покидает стор: когда проекции начнут расходиться, менять придётся
 * здесь, а не в хендлере.
 *
 * Защитной копии здесь **нет намеренно**. Раньше стоял ручной спред пяти веток
 * с обещанием «клиент не сможет испортить состояние стора»; обещание было
 * ложным дважды. Во-первых, спред покрывал половину дерева — `routes[]`,
 * `contacts[]` и `cargo` оставались общими объектами. Во-вторых, копия не нужна
 * вовсе: ответ уходит через `HttpResponse.json`, то есть сериализуется, и
 * клиент физически не может получить ссылку на объект стора. Проверено
 * мутацией: тест «мутация ответа не меняет состояние» проходил одинаково с
 * глубокой копией, с поверхностной и вовсе без копии — он проверял свойство
 * транспорта, а не этого кода.
 * @param entity Каноническая сущность аукциона.
 * @returns Ответ `GET /auctions/{auctionUuid}`.
 */
export const toShowResponse = (entity: AuctionEntity): AuctionShowResponseDto => entity.detail;
