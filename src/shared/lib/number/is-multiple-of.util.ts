/** Допуск сравнения: шаг может быть дробным, а float — неточным. */
const EPSILON = 1e-9;

/**
 * Проверяет кратность значения шагу ставки.
 *
 * Прямое `value % step === 0` здесь неверно: шаг из схемы может быть дробным
 * (`step: number|null`), а `30000.3 % 0.1` в двоичной арифметике даёт не ноль —
 * форма отклоняла бы корректную ставку с необъяснимой для пользователя ошибкой.
 *
 * **Неположительный шаг = отсутствие ограничения, а не ошибка валидации.**
 * `minimum` у `step` в схеме не объявлен, поэтому отрицательное значение
 * технически возможно и означает испорченные данные. Отклонять из-за них любую
 * цену нельзя: это запретило бы единственное бизнес-действие приложения, и
 * пользователь ничего не смог бы с этим сделать. Аномалия нормализуется на
 * границе маппера (`step <= 0` → «шага нет»), а решение о её видимости
 * принимается там же — чистая функция для этого неподходящее место.
 * @param value Проверяемое значение — цена из формы ставки.
 * @param step Шаг из detail DTO. `null`, `undefined` и любое `<= 0` означают «шага нет».
 * @returns `true`, если значение кратно шагу или шаг не задан.
 */
export const isMultipleOf = (value: number, step: number | null | undefined): boolean => {
  if (step === null || step === undefined || step <= 0) return true;

  const remainder = Math.abs(value % step);

  return remainder < EPSILON || Math.abs(remainder - step) < EPSILON;
};
