/**
 * Типографские символы, которые нельзя писать в исходнике самим символом:
 * визуально они неотличимы от обычных, и расхождение всплывает как падение
 * теста на строках, выглядящих одинаково («'30 000 ₽' !== '30 000 ₽'»).
 *
 * Одна константа на проект, а не по копии в каждом файле: два разных `NBSP` в
 * двух файлах — это ровно тот баг, который и случился в фазе 2.
 */

/** Неразрывный пробел, U+00A0. Разделитель разрядов и склейка «сумма ₽». */
export const NBSP = '\u00A0';

/**
 * Математический минус, U+2212 — не дефис U+002D.
 * Отличается по ширине и не путается с прочерком «нет данных».
 */
export const MINUS = '\u2212';

/** Прочерк для отсутствующего значения. */
export const DASH = '\u2014';
