import { describe, expect, it } from 'vitest';

import { DASH } from '../string/typography.const';

import { formatDateRange } from './format-date-range.util';

/** Текущий год: даты внутри него печатаются без года. */
const currentYear = new Date().getFullYear();

/** Дата в текущем году — иначе тест зависел бы от того, когда его запустили. */
const thisYear = (monthDay: string, time: string): string =>
  `${String(currentYear)}-${monthDay}T${time}`;

describe('formatDateRange: диапазон дат для карточки и detail', () => {
  it('одна граница — день, месяц и время', () => {
    expect(formatDateRange(thisYear('05-26', '10:00:00'), null)).toBe('26 мая, 10:00');
  });

  it('если задана только вторая граница — она и печатается', () => {
    expect(formatDateRange(null, thisYear('05-27', '18:30:00'))).toBe('27 мая, 18:30');
  });

  it('две даты в разные дни соединяются стрелкой', () => {
    expect(formatDateRange(thisYear('05-26', '10:00:00'), thisYear('05-27', '18:30:00'))).toBe(
      '26 мая, 10:00 → 27 мая, 18:30',
    );
  });

  it('переход через границу месяца печатается полностью', () => {
    // Логика «не повторять дату» опирается на день, а не на число: 31 мая и
    // 1 июня — разные дни, и обе даты обязаны остаться.
    expect(formatDateRange(thisYear('05-31', '10:00:00'), thisYear('06-01', '18:00:00'))).toBe(
      '31 мая, 10:00 → 1 июня, 18:00',
    );
  });

  it('две даты в один день не повторяют дату дважды', () => {
    expect(formatDateRange(thisYear('05-26', '10:00:00'), thisYear('05-26', '18:00:00'))).toBe(
      '26 мая, 10:00 → 18:00',
    );
  });

  it('одинаковые дата и время не превращаются в диапазон', () => {
    const value = thisYear('05-26', '10:00:00');

    expect(formatDateRange(value, value)).toBe('26 мая, 10:00');
  });

  it('полночь печатается как 00:00, а не пропадает', () => {
    expect(formatDateRange(thisYear('05-26', '00:00:00'), null)).toBe('26 мая, 00:00');
  });

  it('дата не текущего года показывает год', () => {
    // Иначе «26 мая» у декабрьского аукциона с погрузкой в январе означает
    // не ту дату, и ошибку никто не заметит.
    expect(formatDateRange('2019-05-26T10:00:00', null)).toBe('26 мая 2019, 10:00');
  });

  it('диапазон через границу года показывает год у обеих границ', () => {
    expect(formatDateRange('2019-12-31T22:00:00', '2020-01-01T10:00:00')).toBe(
      '31 декабря 2019, 22:00 → 1 января 2020, 10:00',
    );
  });

  it('порядок границ не переставляется молча', () => {
    // Перевёрнутый диапазон — это ошибка данных сервера. Показать его как есть
    // честнее, чем скрыть перестановкой.
    expect(formatDateRange(thisYear('05-27', '10:00:00'), thisYear('05-26', '18:00:00'))).toBe(
      '27 мая, 10:00 → 26 мая, 18:00',
    );
  });

  it('время не сдвигается: в ответах контракта смещения нет (⑮)', () => {
    // Разбор через `new Date(value)` дал бы сдвиг на смещение зоны, и «10:00»
    // превратилось бы в «13:00» — тихий баг, который видно только глазами.
    expect(formatDateRange(thisYear('05-26', '10:00:00'), null)).toContain('10:00');
  });

  it('пустые и неразбираемые значения дают прочерк', () => {
    expect(formatDateRange(null, null)).toBe(DASH);
    expect(formatDateRange('', '')).toBe(DASH);
    expect(formatDateRange('26.05.2026', null)).toBe(DASH);
  });
});
