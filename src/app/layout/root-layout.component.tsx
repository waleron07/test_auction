import { Outlet } from '@tanstack/react-router';

import { PageLayout } from '@/shared/ui';
import { AppHeader } from '@/widgets/app-header';

/**
 * Общая рамка страницы для всех маршрутов: шапка со сквозной навигацией плюс
 * контейнер контента.
 *
 * Шапка живёт здесь, а не в отдельных страницах, потому что дорога назад к
 * списку нужна на каждой из них одинаково — и раньше её не было ни на одной.
 * `<AppHeader>` намеренно **вне** `PageLayout`: тот рендерит `<main>`, а
 * шапке место снаружи основного содержимого страницы.
 *
 * Вынесен из `__root.tsx` отдельным файлом, потому что это React-компонент, а
 * задание требует суффикс `*.component.tsx` для **всех** компонентов. Имена
 * файлов маршрутов диктует file-based routing TanStack Router (`bet.tsx` →
 * `/bet`), переименовать их нельзя — поэтому компоненты из них выносятся, а в
 * маршруте остаётся только конфигурация.
 */
export const RootLayout = () => (
  <>
    <AppHeader />
    <PageLayout>
      <Outlet />
    </PageLayout>
  </>
);
